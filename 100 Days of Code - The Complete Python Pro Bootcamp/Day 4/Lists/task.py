#List
fruits = ["Cherry", "Apple", "Pear"]

#To access 1st element in list
print(fruits[0])

#To access data with Negative Indices
print(fruits[-1]) #it should print 1st element from backside

#Modifying Items
fruits = ["Cherry", "Apple", "Pear"]
fruits[0] = "Orange" #it will modify the 1st element in the list
print(fruits)

#Adding Items to list
fruits = ["Cherry", "Apple", "Pear"]
fruits.append("Orange")


